"""Serial Scale Driver and Contract Service for XL Burguer (Legacy Compatibility Stub).
NOTE: In XL Burguer, physical scale hardware integration is officially deprecated and disabled in the UI.
All sales operate on prepared items (units) with recipes tracked in grams.
This module is maintained exclusively for backward compatibility with contract tests.
"""

from dataclasses import dataclass
import logging
import os
import random
import re
import threading
import time
from typing import Callable, Optional, Tuple

try:
    import serial
    import serial.tools.list_ports
    SERIAL_AVAILABLE = True
except ImportError:
    SERIAL_AVAILABLE = False


@dataclass
class WeightReading:
    """Strict contract for scale readings."""
    value: float               # Raw numeric value as reported by scale
    unit: str                  # "kg", "g", or "lb"
    stable: bool               # True if scale flagged reading as stable (ST)
    is_mock: bool              # True if generated by software simulation
    grams: float = 0.0         # Exact normalized weight in grams
    error: Optional[str] = None # Error explanation if reading failed
    raw_reading: str = ""      # Raw ASCII text buffer from serial port

    def __post_init__(self):
        if self.grams == 0.0 and self.value != 0.0:
            u = self.unit.lower().strip()
            if u == "kg":
                self.grams = round(self.value * 1000.0, 3)
            elif u == "lb":
                self.grams = round(self.value * 500.0, 3)
            else:
                self.grams = round(self.value, 3)

    @property
    def is_valid(self) -> bool:
        """Reading is usable for sale if no error, stable, and positive weight."""
        return self.error is None and self.stable and self.grams > 0.0

    def __iter__(self):
        """Allow tuple unpacking (value, unit) for backward compatibility."""
        yield self.value
        yield self.unit


class SerialScaleDriver:
    """Non-blocking hardware driver for electronic weighing scales."""

    def __init__(
        self,
        port: Optional[str] = None,
        baudrate: int = 9600,
        timeout: float = 0.3,
        force_mock: bool = False,
        allow_mock: Optional[bool] = None
    ):
        self.port = port
        self.baudrate = baudrate
        self.timeout = timeout

        # Production rule: Mock is DISABLED unless explicitly allowed or environment flag is set
        env_mock = (
            os.environ.get("XLBURGUER_MOCK_SCALE", "").strip() in ("1", "true", "True")
            or os.environ.get("SANDIEGO_MOCK_SCALE", "").strip() in ("1", "true", "True")
        )
        if allow_mock is None:
            self.allow_mock = force_mock or env_mock
        else:
            self.allow_mock = allow_mock or force_mock or env_mock

        self.is_mock_mode = force_mock
        self._serial_handle = None
        self._lock = threading.Lock()
        self._last_mock_weight = 0.750  # Starting simulated weight (0.750 kg)

        if not self.is_mock_mode:
            self._initialize_connection()

    def _initialize_connection(self) -> None:
        """Attempt to probe physical COM port safely without blocking."""
        if not SERIAL_AVAILABLE:
            if not self.allow_mock:
                logging.warning("PySerial no está instalado y el modo simulado está deshabilitado.")
            self.is_mock_mode = self.allow_mock
            return

        try:
            available_ports = [p.device for p in serial.tools.list_ports.comports()] if hasattr(serial.tools, 'list_ports') else []
            if not available_ports and not self.port:
                logging.info("No se detectaron puertos COM físicos para la báscula.")
                self.is_mock_mode = self.allow_mock
                return

            target_port = self.port or (available_ports[0] if available_ports else None)
            if not target_port:
                self.is_mock_mode = self.allow_mock
                return

            self._serial_handle = serial.Serial(
                port=target_port,
                baudrate=self.baudrate,
                bytesize=serial.EIGHTBITS,
                parity=serial.PARITY_NONE,
                stopbits=serial.STOPBITS_ONE,
                timeout=self.timeout,
                write_timeout=self.timeout
            )
            self.is_mock_mode = False
            logging.info("Báscula conectada físicamente en puerto: %s", target_port)
        except Exception as e:
            logging.info("No se pudo abrir báscula en puerto físico (%s).", e)
            self._serial_handle = None
            self.is_mock_mode = self.allow_mock

    def read_reading(self) -> WeightReading:
        """Read weight synchronously returning a structured WeightReading."""
        with self._lock:
            # 1. Attempt Physical Reading
            if not self.is_mock_mode and self._serial_handle:
                try:
                    self._serial_handle.reset_input_buffer()
                    raw_bytes = self._serial_handle.readline()
                    raw_line = raw_bytes.decode('ascii', errors='ignore').strip()

                    if not raw_line:
                        return WeightReading(
                            value=0.0,
                            unit="kg",
                            stable=False,
                            is_mock=False,
                            grams=0.0,
                            error="Sin respuesta de la báscula (timeout)",
                            raw_reading=""
                        )

                    # Determine stability: ST=Stable, US=Unstable
                    upper_raw = raw_line.upper()
                    is_stable = True
                    if "US" in upper_raw:
                        is_stable = False
                    elif "ST" in upper_raw:
                        is_stable = True

                    # Extract numeric value
                    match = re.search(r'([-+]?[0-9]+\.?[0-9]*)', raw_line)
                    if match:
                        val = float(match.group(1))
                        unit = "g" if (" g" in raw_line.lower() or raw_line.lower().endswith("g")) and "kg" not in raw_line.lower() else "kg"

                        if unit == "kg":
                            grams = round(val * 1000.0, 2)
                        elif unit == "lb":
                            grams = round(val * 500.0, 2)
                        else:
                            grams = round(val, 2)

                        if val <= 0:
                            return WeightReading(
                                value=val,
                                unit=unit,
                                stable=False,
                                is_mock=False,
                                grams=grams,
                                error="Báscula en cero o peso no positivo",
                                raw_reading=raw_line
                            )

                        if not is_stable:
                            return WeightReading(
                                value=val,
                                unit=unit,
                                stable=False,
                                is_mock=False,
                                grams=grams,
                                error="Peso inestable en la báscula",
                                raw_reading=raw_line
                            )

                        return WeightReading(
                            value=val,
                            unit=unit,
                            stable=True,
                            is_mock=False,
                            grams=grams,
                            raw_reading=raw_line
                        )
                    else:
                        return WeightReading(
                            value=0.0,
                            unit="kg",
                            stable=False,
                            is_mock=False,
                            grams=0.0,
                            error="Trama de báscula no reconocida",
                            raw_reading=raw_line
                        )
                except Exception as e:
                    logging.warning("Error leyendo báscula física: %s.", e)
                    if not self.allow_mock:
                        return WeightReading(
                            value=0.0,
                            unit="kg",
                            stable=False,
                            is_mock=False,
                            grams=0.0,
                            error=f"Fallo de comunicación con báscula: {e}"
                        )
                    self.is_mock_mode = True

            # 2. Check Mock Mode
            if self.is_mock_mode and self.allow_mock:
                variation = random.choice([-0.05, 0.0, 0.05, 0.10, -0.10, 0.15])
                new_weight = round(self._last_mock_weight + variation, 3)
                self._last_mock_weight = max(0.250, min(3.500, new_weight))
                val = self._last_mock_weight
                return WeightReading(
                    value=val,
                    unit="kg",
                    stable=True,
                    is_mock=True,
                    grams=round(val * 1000.0, 2),
                    raw_reading=f"MOCK ST,{val:.3f}kg"
                )

            # 3. Scale disconnected in production without mock permission
            return WeightReading(
                value=0.0,
                unit="kg",
                stable=False,
                is_mock=False,
                grams=0.0,
                error="Báscula no conectada. Conecte el cable serial o active el modo demo."
            )

    def read_weight(self) -> WeightReading:
        """Alias for read_reading guaranteeing contract access while preserving (value, unit) iteration."""
        return self.read_reading()

    def read_weight_async(self, callback: Callable[[WeightReading], None]) -> None:
        """Read weight in a background daemon thread."""
        def worker():
            try:
                time.sleep(0.08)
                reading = self.read_reading()
                callback(reading)
            except Exception as e:
                logging.error("Error en lectura asíncrona de báscula: %s", e)
                callback(WeightReading(
                    value=0.0,
                    unit="kg",
                    stable=False,
                    is_mock=False,
                    grams=0.0,
                    error=str(e)
                ))

        thread = threading.Thread(target=worker, daemon=True)
        thread.start()

    def reconnect(self) -> bool:
        """Attempt to re-detect and reconnect to physical scale COM port."""
        with self._lock:
            if self._serial_handle:
                try:
                    if hasattr(self._serial_handle, "is_open") and self._serial_handle.is_open:
                        self._serial_handle.close()
                except Exception:
                    pass
                self._serial_handle = None
            self._initialize_connection()
            return not self.is_mock_mode

    def close(self) -> None:
        """Close open serial ports cleanly."""
        with self._lock:
            if self._serial_handle:
                try:
                    if hasattr(self._serial_handle, "is_open") and self._serial_handle.is_open:
                        self._serial_handle.close()
                except Exception:
                    pass
            self._serial_handle = None
